CREATE TABLE profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    headline VARCHAR(255),
    city VARCHAR(255),
    story VARCHAR(2000),
    interests VARCHAR(1000),
    phone_number VARCHAR(255) UNIQUE,
    email VARCHAR(255) UNIQUE,
    account_id VARCHAR(255) UNIQUE,
    password_hash VARCHAR(255),
    gender VARCHAR(255),
    instagram_handle VARCHAR(255),
    verification_status VARCHAR(255),
    instagram_verified BOOLEAN NOT NULL,
    subscription_active BOOLEAN NOT NULL,
    credits_balance INTEGER NOT NULL,
    admin BOOLEAN NOT NULL,
    voice_recording_submitted BOOLEAN NOT NULL
);

CREATE UNIQUE INDEX uk_profiles_email_lower ON profiles (LOWER(email));
CREATE INDEX idx_profiles_verification_status ON profiles (verification_status);

CREATE TABLE connection_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT NOT NULL REFERENCES profiles (id),
    recipient_id BIGINT NOT NULL REFERENCES profiles (id),
    status VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_connection_requests_participants UNIQUE (requester_id, recipient_id)
);

CREATE INDEX idx_connection_requests_requester_created
    ON connection_requests (requester_id, created_at DESC);
CREATE INDEX idx_connection_requests_recipient_created
    ON connection_requests (recipient_id, created_at DESC);

CREATE TABLE chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_request_id BIGINT NOT NULL REFERENCES connection_requests (id),
    sender_id BIGINT NOT NULL REFERENCES profiles (id),
    body VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_chat_messages_conversation_created
    ON chat_messages (connection_request_id, created_at);

CREATE TABLE instagram_shares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_request_id BIGINT NOT NULL REFERENCES connection_requests (id),
    sender_id BIGINT NOT NULL REFERENCES profiles (id),
    handle VARCHAR(255) NOT NULL,
    shared_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_instagram_shares_connection_sender UNIQUE (connection_request_id, sender_id)
);

CREATE TABLE credit_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL REFERENCES profiles (id),
    connection_request_id BIGINT REFERENCES connection_requests (id),
    amount INTEGER NOT NULL,
    balance_after INTEGER NOT NULL,
    reason VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_credit_transactions_profile_created
    ON credit_transactions (profile_id, created_at DESC);

CREATE TABLE voice_verification_recordings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL UNIQUE REFERENCES profiles (id),
    content_type VARCHAR(255) NOT NULL,
    recording BYTEA NOT NULL
);
