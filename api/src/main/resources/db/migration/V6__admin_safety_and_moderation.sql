ALTER TABLE profiles
    ADD COLUMN suspended BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE safety_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_profile_id BIGINT NOT NULL REFERENCES profiles (id),
    reported_profile_id BIGINT NOT NULL REFERENCES profiles (id),
    category VARCHAR(40) NOT NULL,
    details VARCHAR(1000) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    reviewed_at TIMESTAMP
);

CREATE INDEX idx_safety_reports_status_created
    ON safety_reports (status, created_at);
CREATE INDEX idx_safety_reports_reported_profile
    ON safety_reports (reported_profile_id, created_at DESC);
