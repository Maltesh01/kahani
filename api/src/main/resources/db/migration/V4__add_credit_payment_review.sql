CREATE TABLE credit_purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL REFERENCES profiles (id),
    package_code VARCHAR(40) NOT NULL,
    amount_rupees INTEGER NOT NULL CHECK (amount_rupees > 0),
    credits INTEGER NOT NULL CHECK (credits > 0),
    payment_reference VARCHAR(120) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    created_at TIMESTAMP NOT NULL,
    reviewed_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX idx_credit_purchases_status_created
    ON credit_purchases (status, created_at);
CREATE INDEX idx_credit_purchases_profile_created
    ON credit_purchases (profile_id, created_at DESC);
